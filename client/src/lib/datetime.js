/**
 * Human-friendly timestamps for status timelines and order cards.
 * The API sends ISO-8601 UTC strings; the browser renders them in local time.
 */
export function formatDateTime(value) {
  if (!value) return '';
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return '';

  return date.toLocaleString('en-MY', {
    day: 'numeric',
    month: 'short',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  });
}
